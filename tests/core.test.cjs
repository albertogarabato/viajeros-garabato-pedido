const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../core.js'),'utf8'),context);
const core = context.TravelCore;
assert.equal(core.combinations('2027-04-10','2027-04-17',3,'2026-11-06').length,49);
assert.equal(core.combinations('2027-04-10','2027-04-17',0,'2026-11-06').length,1);
assert.equal(core.combinations('2027-04-10','2027-04-17',3,'2026-11-06')[0].out,'2027-04-10');
assert.ok(core.combinations('2027-01-01','2027-01-02',7,'2027-01-01').every(p=>p.out>='2027-01-01'&&p.ret>=p.out));
assert.throws(()=>core.combinations('2027-04-17','2027-04-10',3,'2026-11-06'));
assert.throws(()=>core.combinations('2027-02-30','2027-04-10',3,'2026-11-06'));
assert.throws(()=>core.combinations('2026-11-05','2027-04-10',3,'2026-11-06'));
new vm.Script(fs.readFileSync(path.join(__dirname,'../app.js'),'utf8'));
console.log('Fechas y scripts verificados.');
